#!/usr/bin/env python3
"""
Классификатор обращений и генератор черновиков ответов.

Категории:
  - справка
  - жалоба
  - другое
"""

import sys
import os
import re
from typing import Tuple


def clean_text(text: str) -> str:
    """Удаляет нумерацию в начале строки, нормализует дефисы и пробелы."""
    text = text.strip()
    text = re.sub(r"^\d+[\)\.]\s*", "", text).strip()
    # Заменяем неразрывные дефисы и тире на стандартный дефис
    text = text.replace("\u2011", "-").replace("\u2013", "-").replace("\u2014", "-")
    return text


def classify_and_respond(message: str) -> Tuple[str, str]:
    """
    Классифицирует обращение и генерирует черновик ответа на русском языке.
    Возвращает кортеж (category, draft_reply).
    """
    cleaned = clean_text(message)
    lower = cleaned.lower()

    # 1. Проверка на категорию "справка"
    # Запросы на получение документов, выписок, справок
    is_certificate = any(k in lower for k in [
        "справк", "выписк", "документ об уч", "подтверждение обучен", "справку"
    ])

    # 2. Проверка на категорию "жалоба"
    # Недовольство качеством, сбои, технические проблемы, поломки
    is_complaint = any(k in lower for k in [
        "холодн", "очеред", "пропал", "не работает", "сломал",
        "грязн", "плох", "жалоб", "претензи", "не ловит", "ужасн", "сбой"
    ])

    # Определение категории и контекстного ответа
    if is_certificate:
        category = "справка"
        if "месте уч" in lower or "обучен" in lower or "студент" in lower:
            draft = (
                "Здравствуйте! Справку об обучении можно заказать онлайн "
                "в личном кабинете студента (раздел «Услуги и справки») "
                "либо получить в студенческом отделе (кабинет 101, пн–пт с 09:00 до 18:00). "
                "Срок готовности обычно составляет 1–2 рабочих дня."
            )
        else:
            draft = (
                "Здравствуйте! Вы можете заказать необходимую справку через личный кабинет "
                "или обратиться в единое окно обслуживания студентов. "
                "Уточните, пожалуйста, требуемый вид справки и место предоставления."
            )

    elif is_complaint:
        category = "жалоба"
        if "столов" in lower or "ед" in lower or "питани" in lower:
            draft = (
                "Здравствуйте! Приносим извинения за доставленные неудобства. "
                "Информация передана администрации столовой и службе контроля качества питания: "
                "мы проверим температурный режим блюд на раздаче и график работы касс для сокращения очередей."
            )
        elif "wi-fi" in lower or "вайфай" in lower or "интернет" in lower or "сеть" in lower:
            draft = (
                "Здравствуйте! Благодарим за сигнал. Заявка зарегистрирована и передана "
                "в отдел технической поддержки. Инженеры уже проводят диагностику сетевого оборудования "
                "для скорейшего восстановления доступа к Wi-Fi."
            )
        else:
            draft = (
                "Здравствуйте! Приносим извинения за возникшие неудобства. "
                "Ваше обращение зафиксировано и направлено в профильную службу для устранения проблемы. "
                "Мы свяжемся с вами по итогам проверки."
            )

    else:
        category = "другое"
        if "консультаци" in lower or "записаться" in lower:
            draft = (
                "Здравствуйте! Записаться на консультацию можно в личном кабинете в разделе "
                "«Электронная запись» или обратившись напрямую в учебную часть. "
                "Подскажите, пожалуйста, к какому преподавателю или специалисту вы планируете записаться?"
            )
        elif "парковк" in lower or "машин" in lower or "авто" in lower:
            draft = (
                "Здравствуйте! Гостевая парковка находится с северной стороны главного корпуса "
                "(въезд со стороны улицы Университетской через шлагбаум №2). "
                "Для въезда сообщите сотруднику охраны цель визита и номер автомобиля."
            )
        else:
            draft = (
                "Здравствуйте! Спасибо за обращение. Мы приняли ваш запрос в обработку. "
                "При необходимости предоставить дополнительные детали, пожалуйста, ответьте на это сообщение."
            )

    return category, draft


def main():
    # Путь к файлу по умолчанию или из аргументов командной строки
    file_path = sys.argv[1] if len(sys.argv) > 1 else "messages.txt"

    if not os.path.exists(file_path):
        print(f"Ошибка: файл '{file_path}' не найден.", file=sys.stderr)
        sys.exit(1)

    with open(file_path, "r", encoding="utf-8") as f:
        lines = [line.strip() for line in f.readlines() if line.strip()]

    print("=" * 80)
    print(f"ОБРАБОТКА ОБРАЩЕНИЙ ИЗ ФАЙЛА: {file_path}")
    print("=" * 80)

    for i, line in enumerate(lines, 1):
        category, draft_reply = classify_and_respond(line)
        print(f"\nОбращение #{i}:")
        print(f"  Текст:      {line}")
        print(f"  Категория:  {category}")
        print(f"  Черновик:   {draft_reply}")
        print("-" * 80)


if __name__ == "__main__":
    main()
